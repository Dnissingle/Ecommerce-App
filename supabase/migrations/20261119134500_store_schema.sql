create policy "Anyone reads active categories" on public.categories
  for select to anon, authenticated using (is_active);
drop policy if exists "Anyone reads active products" on public.products;
create policy "Anyone reads active products" on public.products
  for select to anon using (is_active);
drop policy if exists "Authenticated reads products" on public.products;
create policy "Authenticated reads products" on public.products
  for select to authenticated using (true);

drop policy if exists "Users manage own cart" on public.cart_items;
create policy "Users manage own cart" on public.cart_items
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users read own orders" on public.orders;
create policy "Users read own orders" on public.orders
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users read own order items" on public.order_items;
create policy "Users read own order items" on public.order_items
  for select to authenticated using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
        and orders.user_id = (select auth.uid())
    )
  );

drop function if exists public.place_order();
drop function if exists public.place_order(text, text);
create function public.place_order(
  p_delivery_address text,
  p_phone text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  item record;
  created_order_id bigint;
  order_total numeric(10, 2) := 0;
  item_count integer := 0;
begin
  if current_user_id is null then
    raise exception 'Sign in before placing an order';
  end if;
  if length(trim(coalesce(p_delivery_address, ''))) < 8 then
    raise exception 'Enter a complete delivery address';
  end if;
  if length(trim(coalesce(p_phone, ''))) < 7 then
    raise exception 'Enter a valid phone number';
  end if;

  insert into public.orders (user_id, delivery_address, phone, total_amount)
  values (current_user_id, trim(p_delivery_address), trim(p_phone), 0)
  returning id into created_order_id;

  for item in
    select cart.product_id, cart.quantity, product.name, product.unit,
           product.price, product.stock_quantity, product.is_active
    from public.cart_items as cart
    join public.products as product on product.id = cart.product_id
    where cart.user_id = current_user_id
    order by product.id
    for update of cart, product
  loop
    item_count := item_count + 1;
    if not item.is_active then
      raise exception 'A product in your cart is no longer available';
    end if;
    if item.stock_quantity < item.quantity then
      raise exception 'Not enough stock for %', item.name;
    end if;
    order_total := order_total + item.price * item.quantity;

    insert into public.order_items (order_id, product_id, name, quantity, unit, unit_price)
    values (created_order_id, item.product_id, item.name, item.quantity, item.unit, item.price);

    update public.products
    set stock_quantity = stock_quantity - item.quantity
    where id = item.product_id;
  end loop;

  if item_count = 0 then
    raise exception 'Your cart is empty';
  end if;

  update public.orders
  set total_amount = order_total
  where id = created_order_id;

  delete from public.cart_items where user_id = current_user_id;
  return created_order_id;
end;
$$;

revoke all on function public.place_order(text, text) from public, anon;
